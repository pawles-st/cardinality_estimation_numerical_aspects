impl GumbelTransform for TaylorIntegerGumbel {
    #[inline]
    fn quantile(&self, q: f32) -> f32 {
        // Double-log Gumbel quantile function
        -f32::ln(-f32::ln(q))
    }

    #[inline(always)]
    fn from_bits_fixed(&self, bits: u32) -> i32 {
        if bits == 0 {
            return -1048576; // -16.0 in Q16.16
        }

        let is_high = bits >= 0x80000000;
        let (k_prime, m) = if is_high {
            let v = !bits;
            let k = v.leading_zeros();
            let k_mapped = k.min(31);
            // Use wrapping_shl to avoid panic on k=31 (shift 32)
            let m = (v.wrapping_shl(k_mapped).wrapping_shl(1)) >> 28;
            (k_mapped + 32, m)
        } else {
            let k = bits.leading_zeros().max(1);
            let k_mapped = k.min(32);
            let m = (bits.wrapping_shl(k_mapped).wrapping_shl(1)) >> 28;
            (k_mapped - 1, m)
        };

        GUMBEL_LUT[((k_prime << 4) | (m & 0xF)) as usize]
    }

    #[inline(always)]
    fn from_bits(&self, bits: u32) -> f32 {
        self.from_bits_fixed(bits) as f32 * (1.0 / 65536.0)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_taylor_integer_accuracy() {
        let taylor_int = TaylorIntegerGumbel::new();
        
        // Test various ranges
        let mut test_cases = Vec::new();
        for i in 1..32 {
            test_cases.push(1 << i);
            test_cases.push((1 << i) | (1 << (i-1)));
            test_cases.push(!(1 << i));
        }
        test_cases.push(0x80000000);
        test_cases.push(0x40000000);
        test_cases.push(0xC0000000);

        for bits in test_cases {
            if bits == 0 || bits == 0xFFFFFFFF { continue; }
            let v = !bits;
            if v < 16 && bits >= 0x80000000 { continue; } // LUT steps are larger here
            
            let u = bits as f64 / 4294967296.0;
            let expected = -(-u.ln()).ln();
            let actual = taylor_int.from_bits(bits) as f64;
            
            let diff = (expected - actual).abs();
            // Accuracy threshold for LUT with 4-bit mantissa indexing
            assert!(diff < 0.1, "Failed at bits={:08x}, u={}, expected={}, actual={}, diff={}", bits, u, expected, actual, diff);
        }
    }

    #[test]
    fn test_taylor_integer_bias() {
        let icdf = ICDFGumbel::new();
        let taylor_int = TaylorIntegerGumbel::new();
        let mut sum_diff = 0.0;
        let n = 100000;
        for i in 1..=n {
            let bits = (i as u64 * 0xFFFFFFFF / n as u64) as u32;
            let q = mantissa_to_float(bits);
            if q < 0.001 || q > 0.999 { continue; } // Stay in f32 reliable range
            let expected = icdf.quantile(q);
            let actual = taylor_int.from_bits(bits);
            sum_diff += actual - expected;
        }
        let avg_bias = sum_diff / n as f32;
        println!("TaylorIntegerGumbel Avg Bias: {}", avg_bias);
        assert!(avg_bias.abs() < 0.01);
    }
}
