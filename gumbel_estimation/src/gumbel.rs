impl GumbelTransform for SplineGumbel {
    #[inline]
    fn quantile(&self, q: f32) -> f32 {
        self.from_bits((q * 4294967296.0) as u32)
    }

    #[inline(always)]
    fn from_bits_fixed(&self, bits: u32) -> i32 {
        let is_high = bits >> 31;
        let target = bits ^ (0u32.wrapping_sub(is_high));
        
        let k = target.leading_zeros().min(31); 
        let segment_bits = if k < 31 { (target << (k + 1)) >> (32 - 2) } else { 0 };
        
        let idx = (is_high << 7) | (k << 2) | segment_bits;
        let (slope_fixed, intercept_fixed) = GUMBEL_SPLINE_TABLE_FIXED[idx as usize];
        
        // frac is the remaining bits after k+1 (exponent) and 2 (segment)
        let frac_bits = if k < 29 { target << (k + 1 + 2) } else { 0 };
        
        // y_fixed = ((frac_bits as i64 * slope_fixed as i64) >> 32) as i32 + intercept_fixed
        let product = (frac_bits as i64 * slope_fixed as i64) >> 32;
        (product as i32) + intercept_fixed
    }

    #[inline(always)]
    fn from_bits(&self, bits: u32) -> f32 {
        self.from_bits_fixed(bits) as f32 * (1.0 / 65536.0)
    }
}

