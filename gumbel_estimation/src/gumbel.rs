impl GumbelTransform for PadeGumbel {
    #[inline]
    fn quantile(&self, q: f32) -> f32 {
        let u_bits = q.to_bits();
        let exp_bits = (u_bits >> 23) & 0xFF;
        let m = 127 - exp_bits as i32;

        if m == 1 {
            let v = 1.0 - q;
            let w = v / (2.0 - v);
            let z = w * w;
            let num_l = w.mul_add(-8.0 * z, 30.0 * w);
            let den_l = z.mul_add(-9.0, 15.0);
            let y = num_l / den_l;
            -y.ln()
        } else {
            let m_float = f32::from_bits((u_bits & 0x7FFFFF) | 0x3F800000);
            let w = (m_float - 1.0) / (m_float + 1.0);
            let z = w * w;
            let num_l = w.mul_add(-8.0 * z, 30.0 * w);
            let den_l = z.mul_add(-9.0, 15.0);
            let l = num_l / den_l;

            let u = l * INV_M_LN2[m.min(127) as usize];
            
            let num_k = u.mul_add(3.0 * u, -6.0 * u);
            let den_k = u.mul_add(u, u.mul_add(-6.0, 6.0));
            let k = num_k / den_k;

            -(LN_M_LN2[m.min(127) as usize] + k)
        }
    }
}

// Basic bit-hack Gumbel transform
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct BasicBitHackGumbel;
impl BasicBitHackGumbel {
    pub fn new() -> Self{
        Self{}
    }

    #[inline(always)]
    fn bit_hack_ln(&self, x: f32) -> f32 {
        const C2_SIMPLE: f32 = -88.02969186;
        (x.to_bits() as f32).mul_add(C1, C2_SIMPLE)
    }
}
impl GumbelTransform for BasicBitHackGumbel {
    #[inline]
    fn quantile(&self, q: f32) -> f32 {
        let ln_q = self.bit_hack_ln(q);
        -self.bit_hack_ln(-ln_q)
    }
}

// Taylor branching bit-hack Gumbel transform
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct TaylorBitHackGumbel;
impl TaylorBitHackGumbel {
    pub fn new() -> Self {
        Self{}
    }

    #[inline(always)]
    fn bit_hack_ln(&self, x: f32) -> f32 {
        (x.to_bits() as f32).mul_add(C1, C2)
    }
}
impl GumbelTransform for TaylorBitHackGumbel {
    #[inline(always)]
    fn quantile(&self, q: f32) -> f32 {
        if q < 0.9 {
            let log_q = -self.bit_hack_ln(q);
            -self.bit_hack_ln(log_q)
        } else {
            let v = 1.0 - q;
            let base_y = -self.bit_hack_ln(v);
            let taylor = v * v.mul_add(0.20833333, 0.5);
            base_y - taylor
        }
    }

    #[inline(always)]
    fn from_bits(&self, bits: u32) -> f32 {
        let q = mantissa_to_float(bits);
        
        if q < 0.9 {
            let log_q = -self.bit_hack_ln(q);
            -self.bit_hack_ln(log_q)
        } else {
            let v = 1.0 - q;
            let base_y = -self.bit_hack_ln(v);
            let taylor = v * v.mul_add(0.20833333, 0.5);
            base_y - taylor
        }
    }
}

