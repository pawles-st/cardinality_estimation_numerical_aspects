impl GumbelTransform for PadeGumbel {
    #[inline]
    fn quantile(&self, q: f32) -> f32 {
        const C2: f32 = -0.36651292; // ln(ln(2))
        let u_bits = q.to_bits();
        let exp_bits = (u_bits >> 23) & 0xFF;
        let m = 127 - exp_bits as i32;

        let res = if m == 1 {
            let v = 1.0 - q;
            let w = v / (2.0 - v);
            let z = w * w;
            let num_l = w.mul_add(-8.0 * z, 30.0 * w);
            let den_l = z.mul_add(-9.0, 15.0);
            let y = num_l / den_l;
            y.ln()
        } else {
            let m_float = f32::from_bits((u_bits & 0x7FFFFF) | 0x3F800000);
            let w = (m_float - 1.0) / (m_float + 1.0);
            let z = w * w;
            let num_l = w.mul_add(-8.0 * z, 30.0 * w);
            let den_l = z.mul_add(-9.0, 15.0);
            let l = num_l / den_l;

            let u_val = l / (m as f32 * LN_2);
            let num_k = u_val.mul_add(3.0 * u_val, -6.0 * u_val);
            let den_k = u_val.mul_add(u_val, u_val.mul_add(-6.0, 6.0));
            let k = num_k / den_k;

            PADE_LN_TABLE[m.min(127) as usize] + C2 + k
        };
        -res
    }
}

// Piecewise Linear Spline Gumbel transform
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct SplineGumbel;

impl SplineGumbel {
    pub fn new() -> Self {
        Self {}
    }
}

impl GumbelTransform for SplineGumbel {
    #[inline]
    fn quantile(&self, q: f32) -> f32 {
        self.from_bits((q * 4294967296.0) as u32)
    }

    #[inline(always)]
    fn from_bits(&self, bits: u32) -> f32 {
        let is_high = bits >> 31;
        let target = bits ^ (0u32.wrapping_sub(is_high));
        
        let k = target.leading_zeros().min(31); 
        let segment_bits = if k < 31 { (target << (k + 1)) >> (32 - 2) } else { 0 };
        
        let idx = (is_high << 7) | (k << 2) | segment_bits;
        let (slope, intercept) = GUMBEL_SPLINE_TABLE[idx as usize];
        
        // frac is the remaining bits after k+1 (exponent) and 2 (segment)
        let frac_bits = if k < 29 { target << (k + 1 + 2) } else { 0 };
        let frac = (frac_bits as f32) * (1.0 / 4294967296.0);
        
        frac.mul_add(slope, intercept)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_spline_accuracy() {
        let icdf = ICDFGumbel::new();
        let spline = SplineGumbel::new();
        for i in 1..1000 {
            let q = i as f32 / 1000.0;
            let expected = icdf.quantile(q);
            let actual = spline.quantile(q);
            let diff = (expected - actual).abs();
            // Linear spline with 4 segments per octave should be accurate to within ~1e-2
            assert!(diff < 1e-2, "Failed at q={}, expected={}, actual={}, diff={}", q, expected, actual, diff);
        }
    }

    #[test]
    fn test_pade_accuracy() {
        let icdf = ICDFGumbel::new();
        let pade = PadeGumbel::new();
        for i in 1..1000 {
            let q = i as f32 / 1000.0;
            let expected = icdf.quantile(q);
            let actual = pade.quantile(q);
            let diff = (expected - actual).abs();
            // Padé approximant should be accurate to within ~1e-3 in this range
            assert!(diff < 1e-3, "Failed at q={}, expected={}, actual={}, diff={}", q, expected, actual, diff);
        }
    }

    #[test]
    fn test_lut_accuracy() {
        let lut = LUTGumbel::new();
        let mut test_cases = Vec::new();
        for i in 1..32 {
            test_cases.push(1 << i);
            test_cases.push(!(1 << i));
        }
        for bits in test_cases {
            if bits == 0 || bits == 0xFFFFFFFF { continue; }
            let u = bits as f64 / 4294967296.0;
            let expected = -(-u.ln()).ln();
            let actual = lut.from_bits(bits) as f64;
            let diff = (expected - actual).abs();
            if u > 0.001 && u < 0.999 {
                assert!(diff < 0.5, "Failed at bits={:08x}, u={}, expected={}, actual={}, diff={}", bits, u, expected, actual, diff);
            }
        }
    }

    #[test]
    fn test_lut_bias() {
        let icdf = ICDFGumbel::new();
        let lut = LUTGumbel::new();
        let mut sum_diff = 0.0;
        let n = 100000;
        for i in 0..n {
            let bits = (i as u64 * 0xFFFFFFFF / n as u64) as u32;
            let expected = icdf.quantile((bits as f32 + 0.5) / 4294967296.0);
            let actual = lut.from_bits(bits);
            sum_diff += actual - expected;
        }
        let avg_bias = sum_diff / n as f32;
        println!("LUTGumbel Avg Bias: {}", avg_bias);
    }
}

